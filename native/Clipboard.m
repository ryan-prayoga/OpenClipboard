static NSString *const OCSource = @"org.nspasteboard.source";
static NSString *const OCConcealed = @"org.nspasteboard.ConcealedType";
static NSString *const OCOwnWrite = @"dev.ryanprayoga.openclipboard.restore";
static const NSUInteger ImageLimit = 25 * 1024 * 1024;
static const NSTimeInterval PollInterval = 0.125;
static const NSTimeInterval RetryWindow = 3.0;

static NSPasteboard *OCBoard(void) {
    NSUserDefaults *defaults = NSUserDefaults.standardUserDefaults;
    if ([defaults stringForKey:@"OCTestDataDirectory"].length) {
        NSString *testName = [defaults stringForKey:@"OCTestPasteboardName"];
        if (testName.length) return [NSPasteboard pasteboardWithName:testName];
    }
    return NSPasteboard.generalPasteboard;
}


static NSSet<NSString *> *IgnoredTypes(void) {
    static NSSet<NSString *> *types;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        types = [NSSet setWithArray:@[OCConcealed, OCOwnWrite,
            @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType",
            @"com.agilebits.onepassword", @"de.petermaurer.TransientPasteboardType",
            @"com.typeit4me.clipping", @"Pasteboard generator type"]];
    });
    return types;
}

static NSSet<NSString *> *SupportedTypes(void) {
    static NSSet<NSString *> *types;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        types = [NSSet setWithArray:@[NSPasteboardTypeString, NSPasteboardTypeURL,
            NSPasteboardTypePNG, NSPasteboardTypeTIFF, NSPasteboardTypeColor,
            @"public.utf16-external-plain-text", @"public.utf16-plain-text"]];
    });
    return types;
}

static BOOL SetCaretTimeout(AXUIElementRef element, NSTimeInterval deadline) {
    NSTimeInterval remaining = deadline - NSProcessInfo.processInfo.systemUptime;
    if (remaining < 0.001) return NO;
    return AXUIElementSetMessagingTimeout(element, (float)remaining) == kAXErrorSuccess;
}

static id AXAttribute(AXUIElementRef element, CFStringRef name, NSTimeInterval deadline) {
    if (!SetCaretTimeout(element,deadline)) return nil;
    CFTypeRef value = NULL;
    AXUIElementCopyAttributeValue(element,name,&value);
    return CFBridgingRelease(value);
}

static BOOL ReadAXValue(id value, AXValueType type, void *output) {
    return value && CFGetTypeID((__bridge CFTypeRef)value) == AXValueGetTypeID()
        && AXValueGetValue((__bridge AXValueRef)value,type,output);
}

static BOOL IsAXElement(id value) {
    return value && CFGetTypeID((__bridge CFTypeRef)value) == AXUIElementGetTypeID();
}

static id SystemFocusedElement(pid_t pid, NSTimeInterval deadline) {
    AXUIElementRef system = AXUIElementCreateSystemWide();
    id focused = AXAttribute(system,kAXFocusedUIElementAttribute,deadline);
    AXUIElementSetMessagingTimeout(system,0);
    CFRelease(system);
    pid_t focusedPID;
    return IsAXElement(focused) &&
        AXUIElementGetPid((__bridge AXUIElementRef)focused,&focusedPID) == kAXErrorSuccess && focusedPID == pid
        ? focused : nil;
}

static BOOL ValidTextBounds(CGRect rect) {
    return !CGRectIsNull(rect) && isfinite(rect.origin.x) && isfinite(rect.origin.y) &&
        isfinite(rect.size.width) && isfinite(rect.size.height) && rect.size.width >= 0 && rect.size.height > 0;
}

static CGRect BoundsForTextRange(AXUIElementRef element, CFIndex index, CFIndex length, NSTimeInterval deadline) {
    if (!SetCaretTimeout(element,deadline)) return CGRectNull;
    CFRange range = CFRangeMake(index,length);
    AXValueRef input = AXValueCreate(kAXValueTypeCFRange,&range);
    if (!input) return CGRectNull;
    CFTypeRef value = NULL;
    AXUIElementCopyParameterizedAttributeValue(element,kAXBoundsForRangeParameterizedAttribute,input,&value);
    CFRelease(input);
    CGRect rect;
    return ReadAXValue(CFBridgingRelease(value),kAXValueTypeCGRect,&rect) && ValidTextBounds(rect)
        ? rect : CGRectNull;
}

static NSNumber *LineForIndex(AXUIElementRef element, CFIndex index, NSTimeInterval deadline) {
    if (!SetCaretTimeout(element,deadline)) return nil;
    CFTypeRef value = NULL;
    AXUIElementCopyParameterizedAttributeValue(element,kAXLineForIndexParameterizedAttribute,(__bridge CFNumberRef)@(index),&value);
    id line = CFBridgingRelease(value);
    return [line isKindOfClass:NSNumber.class] ? line : nil;
}

static CGRect InsertionBounds(AXUIElementRef element, CFIndex index, NSTimeInterval deadline) {
    CGRect caret = BoundsForTextRange(element,index,0,deadline);
    CGRect glyph = index < LONG_MAX ? BoundsForTextRange(element,index,1,deadline) : CGRectNull;
    BOOL afterGlyph = CGRectIsNull(glyph);
    if (afterGlyph && index > 0) glyph = BoundsForTextRange(element,index-1,1,deadline);
    if (CGRectIsNull(glyph)) return caret;

    // Some AppKit fields return the insertion X correctly but report the preceding line's Y.
    CGFloat x = afterGlyph ? CGRectGetMaxX(glyph) : CGRectGetMinX(glyph);
    if (!CGRectIsNull(caret)) {
        CGFloat insertionX = CGRectGetMinX(caret);
        if (insertionX >= CGRectGetMinX(glyph)-1 && insertionX <= CGRectGetMaxX(glyph)+1) {
            x = insertionX;
        } else if (afterGlyph) {
            NSNumber *line = LineForIndex(element,index,deadline);
            NSNumber *previous = LineForIndex(element,index-1,deadline);
            if (line && previous && line.integerValue > previous.integerValue) {
                return CGRectMake(insertionX,CGRectGetMaxY(glyph),0,CGRectGetHeight(glyph));
            }
        }
    }
    return CGRectMake(x,CGRectGetMinY(glyph),0,CGRectGetHeight(glyph));
}

static CGRect ElementBounds(AXUIElementRef element, NSTimeInterval deadline) {
    CGRect rect;
    if (ReadAXValue(AXAttribute(element,CFSTR("AXFrame"),deadline),kAXValueTypeCGRect,&rect) &&
        ValidTextBounds(rect) && rect.size.width > 0) return rect;
    if (!ReadAXValue(AXAttribute(element,kAXPositionAttribute,deadline),kAXValueTypeCGPoint,&rect.origin) ||
        !ReadAXValue(AXAttribute(element,kAXSizeAttribute,deadline),kAXValueTypeCGSize,&rect.size)) return CGRectNull;
    return ValidTextBounds(rect) && rect.size.width > 0 ? rect : CGRectNull;
}

static BOOL CaretOnScreen(CGRect rect, NSArray<NSScreen *> *screens, NSRect *result) {
    if (CGRectIsNull(rect)) return NO;
    rect.origin.y = NSMaxY(screens.firstObject.frame) - CGRectGetMaxY(rect);
    for (NSScreen *screen in screens) {
        if (NSPointInRect(rect.origin, NSInsetRect(screen.frame,-1,-1))) {
            *result = rect;
            return YES;
        }
    }
    return NO;
}

static BOOL LocateFocusedCaret(id focused, NSArray<NSScreen *> *screens, NSRect *result, NSTimeInterval deadline) {
    NSRect fallback = NSZeroRect;
    BOOL hasFallback = NO;
    // Some editors put the focused child inside the accessible text control.
    for (NSUInteger depth = 0; depth < 3 && IsAXElement(focused); depth++) {
        AXUIElementRef element = (__bridge AXUIElementRef)focused;
        if (NSProcessInfo.processInfo.systemUptime >= deadline) break;
        id role = AXAttribute(element,kAXRoleAttribute,deadline);
        if ([role isEqual:(__bridge NSString *)kAXWindowRole] ||
            [role isEqual:(__bridge NSString *)kAXApplicationRole]) break;
        BOOL textControl = [role isEqual:(__bridge NSString *)kAXTextFieldRole] ||
            [role isEqual:(__bridge NSString *)kAXTextAreaRole] ||
            [role isEqual:(__bridge NSString *)kAXComboBoxRole];
        CFRange selected;
        BOOL hasSelection = ReadAXValue(AXAttribute(element,kAXSelectedTextRangeAttribute,deadline),kAXValueTypeCFRange,&selected) &&
            selected.location >= 0 && selected.length >= 0 && selected.length <= LONG_MAX-selected.location;
        CGRect field = textControl || hasSelection ? ElementBounds(element,deadline) : CGRectNull;
        if (hasSelection) {
            CGRect caret = InsertionBounds(element,selected.location+selected.length,deadline);
            if (!CGRectIsNull(caret) && !CGRectIsNull(field)) {
                if (selected.location == 0 && selected.length == 0) {
                    caret.origin.y = MAX(caret.origin.y,CGRectGetMinY(field));
                }
                CGPoint midpoint = CGPointMake(CGRectGetMinX(caret),CGRectGetMidY(caret));
                if (!CGRectContainsPoint(CGRectInset(field,-8,-8),midpoint)) caret = CGRectNull;
            }
            if (CaretOnScreen(caret,screens,result)) return YES;
        }
        if (!hasFallback && !CGRectIsNull(field) && field.size.width > 8 && field.size.height > 8) {
            // A location inside the editor is still useful when it exposes only its frame.
            CGFloat lineHeight = MIN(24,CGRectGetHeight(field));
            CGRect nearInput = CGRectMake(CGRectGetMinX(field)+6,CGRectGetMinY(field),0,lineHeight);
            hasFallback = CaretOnScreen(nearInput,screens,&fallback);
        }
        focused = AXAttribute(element,kAXParentAttribute,deadline);
    }
    if (hasFallback) *result = fallback;
    return hasFallback;
}

BOOL OCGetCaret(pid_t pid, NSRect *result) {
    if (pid <= 0 || !AXIsProcessTrusted()) return NO;
    NSArray<NSScreen *> *screens = NSScreen.screens;
    if (!screens.count) return NO;

    // Share one budget across the app, its focused elements, and the system fallback.
    NSTimeInterval deadline = NSProcessInfo.processInfo.systemUptime + 0.045;
    AXUIElementRef app = AXUIElementCreateApplication(pid);
    id focused = AXAttribute(app,kAXFocusedUIElementAttribute,deadline);
    CFRelease(app);
    if (LocateFocusedCaret(focused,screens,result,deadline)) return YES;

    id systemFocused = SystemFocusedElement(pid,deadline);
    return systemFocused && (!IsAXElement(focused) ||
        !CFEqual((__bridge CFTypeRef)systemFocused,(__bridge CFTypeRef)focused)) &&
        LocateFocusedCaret(systemFocused,screens,result,deadline);
}

NSArray<NSPasteboardItem *> *OCPasteboardItems(NSArray<NSDictionary *> *parts) {
    NSMutableArray<NSPasteboardItem *> *items = [NSMutableArray array];
    NSUInteger index = NSNotFound;
    NSPasteboardItem *item = nil;
    for (NSDictionary *part in parts) {
        NSUInteger next = [part[@"item"] unsignedIntegerValue];
        if (next != index || !item) {
            item = [NSPasteboardItem new];
            [items addObject:item];
            index = next;
        }
        if (![item setData:part[@"data"] forType:part[@"type"]]) return nil;
    }
    return items;
}

BOOL OCWriteClipboard(NSArray<NSDictionary *> *parts, NSInteger *version) {
    NSArray<NSPasteboardItem *> *items = OCPasteboardItems(parts);
    if (!items.count) return NO;
    for (NSPasteboardItem *item in items) {
        [item setData:[NSData data] forType:OCOwnWrite];
    }
    NSPasteboard *pasteboard = OCBoard();
    [pasteboard clearContents];
    if (![pasteboard writeObjects:items]) return NO;
    *version = pasteboard.changeCount;
    return YES;
}

BOOL OCPostPaste(pid_t destination, NSInteger version) {
    if (NSWorkspace.sharedWorkspace.frontmostApplication.processIdentifier != destination ||
        OCBoard().changeCount != version || !CGPreflightPostEventAccess()) return NO;
    CGEventRef down = CGEventCreateKeyboardEvent(NULL, kVK_ANSI_V, true);
    CGEventRef up = CGEventCreateKeyboardEvent(NULL, kVK_ANSI_V, false);
    BOOL posted = down && up;
    if (posted) {
        CGEventSetFlags(down, kCGEventFlagMaskCommand);
        CGEventSetFlags(up, kCGEventFlagMaskCommand);
        CGEventPostToPid(destination, down);
        CGEventPostToPid(destination, up);
    }
    if (down) CFRelease(down);
    if (up) CFRelease(up);
    return posted;
}

@interface OCRecorder ()
@property(nonatomic, strong) NSTimer *timer;
@property(nonatomic) NSInteger count;
@property(nonatomic, copy) NSString *front;
@property(nonatomic) BOOL switched;
@property(nonatomic) BOOL limitHit;
@property(nonatomic) BOOL inaccessible;
@property(nonatomic) NSInteger retryChange;
@property(nonatomic) NSTimeInterval retryDeadline;
@property(nonatomic) BOOL retryChangedApp;
@property(nonatomic, copy, readwrite) NSString *status;
@property(nonatomic, copy, readwrite) NSString *policy;
@end

@implementation OCRecorder
- (void)startTimer {
    if (self.timer) return;
    [self resetBaseline];
    [NSWorkspace.sharedWorkspace.notificationCenter addObserver:self
        selector:@selector(activeAppChanged:) name:NSWorkspaceDidActivateApplicationNotification object:nil];
    [self updateStatus];
    self.timer = [NSTimer timerWithTimeInterval:PollInterval target:self selector:@selector(tick:)
                                          userInfo:nil repeats:YES];
    self.timer.tolerance = 0.010;
    [NSRunLoop.mainRunLoop addTimer:self.timer forMode:NSRunLoopCommonModes];
}

- (void)activeAppChanged:(NSNotification *)note {
    self.switched = YES;
}

- (void)resetBaseline {
    self.count = OCBoard().changeCount;
    self.front = NSWorkspace.sharedWorkspace.frontmostApplication.bundleIdentifier;
    self.switched = NO;
    self.retryDeadline = 0;
}

- (void)retry {
    self.inaccessible = NO;
    [self resetBaseline];
    [self updateStatus];
}

// Some apps clear the pasteboard first and write large payloads (such as images) or add the
// supported types afterwards without raising the change count again. Look again for a short
// while instead of dropping a copy that was only incomplete when first seen.
- (BOOL)retryIncompleteChange:(NSInteger)current previous:(NSInteger)previous changedApp:(BOOL)changedApp {
    NSTimeInterval now = NSProcessInfo.processInfo.systemUptime;
    if (!self.retryDeadline || self.retryChange != current) {
        self.retryChange = current;
        self.retryDeadline = now + RetryWindow;
    }
    if (now >= self.retryDeadline) return NO;
    self.count = previous;
    self.retryChangedApp = changedApp;
    return YES;
}

- (void)storageFull:(BOOL)full {
    self.limitHit = full;
    [self updateStatus];
}

- (BOOL)updateStatus {
    NSString *policy = OCText(@"Ikuti sistem", @"System default");
    BOOL denied = NO;
    if (@available(macOS 15.4, *)) {
        switch (OCBoard().accessBehavior) {
            case NSPasteboardAccessBehaviorAlwaysAllow: policy = OCText(@"Diizinkan", @"Allowed"); break;
            case NSPasteboardAccessBehaviorAlwaysDeny: policy = OCText(@"Dibatasi", @"Restricted"); denied = YES; break;
            case NSPasteboardAccessBehaviorAsk: policy = OCText(@"Tanya tiap dibaca", @"Ask each time"); break;
            default: break;
        }
    }
    NSString *status = (denied || self.inaccessible) ? OCText(@"Akses clipboard dibatasi", @"Clipboard access restricted")
        : self.limitHit ? OCText(@"Penyimpanan penuh", @"Storage full") : @"";
    if (![self.policy isEqualToString:policy] || ![self.status isEqualToString:status]) {
        self.policy = policy;
        self.status = status;
        if (self.statusChanged) self.statusChanged();
    }
    return denied;
}

- (void)tick:(NSTimer *)timer {
    [self captureNow];
}

- (BOOL)prepareClipboardWrite {
    [self captureNow];
    return self.count == OCBoard().changeCount;
}

- (void)captureNow {
    NSPasteboard *board = OCBoard();
    BOOL denied = [self updateStatus];
    if (self.inaccessible || denied) {
        [self resetBaseline];
        return;
    }
    NSInteger current = board.changeCount;
    NSString *front = NSWorkspace.sharedWorkspace.frontmostApplication.bundleIdentifier;
    NSInteger previous = self.count;
    BOOL changedApp = self.switched || ![self.front isEqualToString:front]
        || (self.retryDeadline && self.retryChange == current && self.retryChangedApp);
    self.count = current;
    self.front = front;
    self.switched = NO;
    if (current == previous) return;

    NSArray<NSString *> *excluded = [NSUserDefaults.standardUserDefaults stringArrayForKey:@"OCExcluded"] ?: @[];
    if (excluded.count && (!front.length || changedApp || current != previous + 1
                           || [excluded containsObject:front])) return;

    NSArray<NSPasteboardItem *> *items = board.pasteboardItems;
    if (!items.count) {
        self.inaccessible = [self updateStatus];
        if (!self.inaccessible) [self retryIncompleteChange:current previous:previous changedApp:changedApp];
        return;
    }
    for (NSPasteboardItem *item in items) {
        for (NSString *type in item.types) {
            if ([IgnoredTypes() containsObject:type] || [type isEqualToString:NSPasteboardTypeFileURL]) return;
        }
        if (excluded.count && [item.types containsObject:OCSource]) {
            NSString *source = [item stringForType:OCSource];
            if (!source.length || [excluded containsObject:source] || ![source isEqualToString:front]) return;
        }
    }

    NSMutableArray<NSDictionary *> *entries = [NSMutableArray array];
    NSString *color = @"";
    NSUInteger size = 0;
    BOOL incomplete = NO;
    for (NSUInteger index = 0; index < items.count; index++) {
        NSPasteboardItem *item = items[index];
        for (NSString *type in item.types) {
            if (![SupportedTypes() containsObject:type]) continue;
            NSData *bytes = [item dataForType:type];
            if (!bytes) {
                incomplete = YES;
                continue;
            }
            if (bytes.length > ImageLimit - size || entries.count >= 1024) return;
            size += bytes.length;
            [entries addObject:@{@"item": @(index), @"type": type, @"data": bytes}];
            if (!color.length && [type isEqualToString:NSPasteboardTypeColor]) {
                // Keep the native archive as-is, and decode the color for the swatch.
                NSPasteboard *temporary = [NSPasteboard pasteboardWithUniqueName];
                [temporary setData:bytes forType:NSPasteboardTypeColor];
                NSColor *native = [[NSColor colorFromPasteboard:temporary]
                                    colorUsingColorSpace:NSColorSpace.sRGBColorSpace];
                [temporary releaseGlobally];
                if (native) {
                    color = [NSString stringWithFormat:@"#%02X%02X%02X",
                        (unsigned)lround(native.redComponent * 255), (unsigned)lround(native.greenComponent * 255),
                        (unsigned)lround(native.blueComponent * 255)];
                }
            }
        }
    }
    if (board.changeCount != current) return;
    if ((incomplete || !entries.count) &&
        [self retryIncompleteChange:current previous:previous changedApp:changedApp]) return;
    if (!entries.count) return;

    OCPart *parts = calloc(entries.count, sizeof(OCPart));
    if (!parts) return;
    NSUInteger index = 0;
    for (NSDictionary *entry in entries) {
        NSData *bytes = entry[@"data"];
        parts[index++] = (OCPart){
            .item = [entry[@"item"] unsignedIntegerValue], .type = [entry[@"type"] UTF8String],
            .data = bytes.bytes, .length = bytes.length,
        };
    }
    OCCaptureResult result = oc_capture(parts, entries.count, color.UTF8String);
    free(parts);
    if (result == OCCaptureBusy) {
        [self retryIncompleteChange:current previous:previous changedApp:changedApp];
    }
}
@end

OCThumbnail oc_thumbnail(const uint8_t *data, size_t length) {
    @autoreleasepool {
        OCThumbnail output = {0};
        NSData *sourceBytes = [NSData dataWithBytesNoCopy:(void *)data length:length freeWhenDone:NO];
        NSDictionary *sourceOptions = @{(__bridge NSString *)kCGImageSourceShouldCache: @NO};
        CGImageSourceRef source = CGImageSourceCreateWithData((__bridge CFDataRef)sourceBytes,
                                                               (__bridge CFDictionaryRef)sourceOptions);
        if (!source) return output;
        NSDictionary *properties = CFBridgingRelease(CGImageSourceCopyPropertiesAtIndex(source, 0, NULL));
        size_t width = [properties[(__bridge NSString *)kCGImagePropertyPixelWidth] unsignedIntegerValue];
        size_t height = [properties[(__bridge NSString *)kCGImagePropertyPixelHeight] unsignedIntegerValue];
        if (!width || !height || width > 40000000 / height) {
            CFRelease(source);
            return output;
        }
        NSDictionary *options = @{
            (__bridge NSString *)kCGImageSourceCreateThumbnailFromImageAlways: @YES,
            (__bridge NSString *)kCGImageSourceThumbnailMaxPixelSize: @300,
            (__bridge NSString *)kCGImageSourceCreateThumbnailWithTransform: @YES,
        };
        CGImageRef image = CGImageSourceCreateThumbnailAtIndex(source, 0, (__bridge CFDictionaryRef)options);
        CFRelease(source);
        if (!image) return output;

        NSMutableData *png = [NSMutableData data];
        CGImageDestinationRef destination = CGImageDestinationCreateWithData((__bridge CFMutableDataRef)png,
                                                                             CFSTR("public.png"), 1, NULL);
        if (destination) {
            CGImageDestinationAddImage(destination, image, NULL);
            if (CGImageDestinationFinalize(destination) && png.length) {
                output.data = malloc(png.length);
                if (output.data) {
                    memcpy(output.data, png.bytes, png.length);
                    output.length = png.length;
                    output.width = width;
                    output.height = height;
                }
            }
            CFRelease(destination);
        }
        CGImageRelease(image);
        return output;
    }
}

void oc_free_thumbnail(uint8_t *data) { free(data); }

size_t oc_character_count(const uint8_t *data, size_t length) {
    @autoreleasepool {
        NSString *text = [[NSString alloc] initWithBytes:data length:length encoding:NSUTF8StringEncoding];
        return OCCharacterCount(text);
    }
